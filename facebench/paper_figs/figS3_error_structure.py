"""
Supplementary Fig. S3 — structure of misclassification, 33-class diagnosis.
thread facebase3d-paper-2026-08-08.

Supports Sec. 2.6 paragraph 3. Fig. 4 in the main text is about leakage and
acquisition-site shift and shows nothing about which diagnoses are confused with
which, so the RASopathy claim had no figure behind it anywhere in the paper.

The paragraph makes a deliberately two-sided claim -- within-family confusion is
ENRICHED but does NOT dominate -- and the figure has to show both halves, or it
would support a stronger statement than the data does. Panel (c) is therefore
not decoration: it is the half that keeps the claim honest.

Source: results/predictions/B2_corrected_ts{1..5}__pointnet2__
softmax__subject__seed{0..4}.npz -- the FIVE TRAINING RUNS with their inference
seeds, 25 files, subject level. Matches \rasWithinFrac (9%), \rasShare (9%)
and \rasEnrich (1x) as regenerated by recognizability.py --family trainseed.

The pre-2026-09-08 version of this figure pooled five inference seeds of ONE
checkpoint and matched the then-published 27% / 3x. That enrichment does not
survive retraining: across the five models the within-family error fraction
runs 2%-18% and never reaches 27%.
"""
import numpy as np
import matplotlib.pyplot as plt
from matplotlib.colors import LinearSegmentedColormap
import figstyle as fs

fs.apply()
PRED = "../../results/predictions/"
RAS = ["Noonan Syndrome", "Costello Syndrome", "CFC"]
RASC, OTHC = "#B03A2E", "#123F63"

# FIVE TRAINING RUNS, each with its five inference seeds -- 25 files. Until
# 2026-09-08 this read B2_corrected__...__seed{0..4}: one training run sampled
# five times, which the docstring called "five seeds pooled". Pooling the sweep
# instead changes what this panel shows materially, because the RASopathy
# clustering it was built to illustrate is largely a property of that one
# checkpoint (within-family error fraction 27% there, 9% across the five
# models). See facebench/eval/recognizability.py.
ds = [np.load(f"{PRED}B2_corrected_ts{t}__pointnet2__softmax__subject__seed{s}.npz",
              allow_pickle=True)
      for t in range(1, 6) for s in range(5)]
names = [str(x) for x in ds[0]["label_names"]]
yt = ds[0]["y_true"]
K = len(names)
ras = [names.index(r) for r in RAS]

# Row-normalised confusion, averaged over seeds.
C = np.zeros((K, K))
for d in ds:
    for t, p in zip(yt, d["y_pred"]):
        C[t, p] += 1
C = C / np.maximum(C.sum(1, keepdims=True), 1)

# Order: RASopathies first so the block is contiguous and legible, then the rest
# alphabetically. Stated in the caption -- a reordered confusion matrix that does
# not say so invites the reader to infer structure from the ordering.
rest = [i for i in range(K) if i not in ras]
order = ras + sorted(rest, key=lambda i: names[i])
Co = C[np.ix_(order, order)]
short = [names[i][:22] for i in order]

# Manual axes placement, not constrained_layout. The matrix carries long y tick
# labels on the left and a colorbar on the right; constrained_layout balances the
# AXES boxes, not the image inside them, so the square image ends up right of the
# figure centre. Placing it explicitly is the only way to centre the image itself.
FIGW, FIGH = fs.DOUBLE, 8.00
fig = plt.figure(figsize=(FIGW, FIGH))
fig.set_layout_engine("none")

IMG_W = 4.15                                   # inches, square
img_l = (FIGW - IMG_W) / 2.0                   # centred on the figure
img_b = FIGH - 0.42 - IMG_W
ax = fig.add_axes([img_l / FIGW, img_b / FIGH, IMG_W / FIGW, IMG_W / FIGH])

cmap = LinearSegmentedColormap.from_list("b", ["#FFFFFF", "#9CC0DC", "#123F63"])
im = ax.imshow(Co, cmap=cmap, vmin=0, vmax=1, aspect="equal",
               interpolation="nearest")
ax.set_xticks(range(K)); ax.set_yticks(range(K))
ax.set_xticklabels(short, rotation=90, fontsize=4.6)
ax.set_yticklabels(short, fontsize=4.6)
for t, lab in zip(ax.get_xticklabels() + ax.get_yticklabels(), short * 2):
    if lab in [n[:22] for n in RAS]:
        t.set_color(RASC); t.set_fontweight("bold")
n = len(ras)
ax.add_patch(plt.Rectangle((-0.5, -0.5), n, n, fill=False, edgecolor=RASC,
                           lw=1.1, zorder=5))
ax.set_xlabel("Predicted diagnosis", fontsize=8)
ax.set_ylabel("True diagnosis", fontsize=8)
ax.set_title("(a)  Subject-level confusion, five-seed mean, row-normalised",
             loc="center", fontsize=8.5, pad=5)
cax = fig.add_axes([(img_l + IMG_W + 0.10) / FIGW, img_b / FIGH,
                    0.11 / FIGW, IMG_W / FIGH])
cb = fig.colorbar(im, cax=cax)
cb.set_label("Fraction of subjects", fontsize=7)
cb.ax.tick_params(labelsize=6.5)

# ── (b) where RASopathy errors go ──────────────────────────────────────────
BOT_H = 1.55
bot_b = 0.62
ax2 = fig.add_axes([1.20 / FIGW, bot_b / FIGH, 1.95 / FIGW, BOT_H / FIGH])
dest = np.zeros(K)
for d in ds:
    yp = d["y_pred"]
    m = np.isin(yt, ras) & (yp != yt)
    for p in yp[m]:
        dest[p] += 1
tot = dest.sum()
top = np.argsort(dest)[::-1][:8]
top = [i for i in top if dest[i] > 0][::-1]
cols = [RASC if i in ras else OTHC for i in top]
ax2.barh(range(len(top)), 100 * dest[top] / tot, color=cols, height=0.7,
         linewidth=0)
ax2.set_yticks(range(len(top)))
ax2.set_yticklabels([names[i][:20] for i in top], fontsize=6.2)
for t, i in zip(ax2.get_yticklabels(), top):
    if i in ras:
        t.set_color(RASC)
ax2.set_xlabel("Share of RASopathy errors (%)", fontsize=7.5)
ax2.set_title("(b)  Destination of RASopathy errors", loc="center", fontsize=8.5,
              pad=5)
ax2.spines["left"].set_visible(False); ax2.tick_params(axis="y", length=0)

# ── (c) enriched, but not dominant ─────────────────────────────────────────
ax3 = fig.add_axes([4.70 / FIGW, bot_b / FIGH, 1.30 / FIGW, BOT_H / FIGH])
within = 100 * dest[ras].sum() / tot
expect = 100 * np.isin(yt, ras).mean()
ax3.bar([0, 1], [expect, within], width=0.55, color=["#B8B8B8", RASC],
        linewidth=0)
ax3.set_xticks([0, 1])
ax3.set_xticklabels(["expected from\nprevalence", "observed"], fontsize=7)
ax3.set_ylabel("Errors staying in group (%)", fontsize=7.3)
ax3.set_ylim(0, 100)
for xx, vv in [(0, expect), (1, within)]:
    ax3.annotate(f"{vv:.0f}%", xy=(xx, vv), xytext=(0, 3),
                 textcoords="offset points", ha="center", fontsize=7.5)
ax3.annotate(f"{within / expect:.1f}$\\times$ enrichment", xy=(0.5, 76),
             ha="center", fontsize=7.5, color=RASC)
# The half of the claim that a bare enrichment number would hide.
ax3.axhline(50, color=fs.INK, lw=0.7, ls=(0, (3, 2)))
ax3.annotate("majority of errors\nleave the group", xy=(0.5, 57), ha="center",
             fontsize=6.6, color=fs.INK)
ax3.set_title("(c)  Enriched, not dominant", loc="center", fontsize=8.5, pad=5)

fs.finish(fig, "../../figures/figS3_error_structure.png", fs.DOUBLE)
print(f"  within-group {within:.1f}%  expected {expect:.1f}%  "
      f"enrichment {within / expect:.2f}x  n_errors={int(tot)}")
print(f"  top destination: {names[top[-1]]} ({100 * dest[top[-1]] / tot:.1f}%)")
