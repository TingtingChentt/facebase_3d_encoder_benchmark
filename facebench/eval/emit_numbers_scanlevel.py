#!/usr/bin/env python3
"""
Emit paper/numbers_leak.tex from the re-scored scan-level arm.
thread facebase3d-paper-2026-08-08.

Follows the same discipline as emit_numbers.py: values are WRITTEN FROM THE CSV,
never typed, and each macro carries the row it came from so it can be checked by
eye. Run after facebench/eval/rerun_scanlevel.py.
"""
import sys
from pathlib import Path
import pandas as pd

PROJECT = Path(__file__).resolve().parents[2]
SRC = PROJECT / "results/scanlevel_summary_ci_all.csv"
CORR = PROJECT / "results/summary_ci.csv"
OUT = PROJECT / "results/paper_macros/numbers_leak.tex"

if not SRC.exists():
    sys.exit(f"missing {SRC} — run rerun_scanlevel.py first")
s = pd.read_csv(SRC)
c = pd.read_csv(CORR)


def row(frame, task, metric):
    r = frame[(frame.task == task) & (frame.encoder == "pointnet2")
              & (frame["head"] == "softmax") & (frame.level == "scan")
              & (frame.metric == metric)]
    if r.empty:
        sys.exit(f"no row for {task}/{metric}")
    return r.iloc[0]


SPECS = [
    # (macro stem, scan-level task, corrected task, metric)
    ("leakSyn",     "B1_scanlevel", "B1_corrected", "accuracy"),
    ("leakDx",      "B2_scanlevel", "B2_corrected", "accuracy"),
    ("leakDxFone",  "B2_scanlevel", "B2_corrected", "macro_f1"),
    ("leakComb",    "C_scanlevel",  "C_corrected",  "accuracy"),
]

L = []
L.append("% " + "=" * 74)
L.append("% numbers_leak.tex — GENERATED by facebench/eval/"
         "emit_numbers_scanlevel.py")
L.append("% Do not edit by hand; re-run the emitter.")
L.append("%")
L.append("% The scan-level ('before') arm of the leakage audit, re-scored under the")
L.append("% SAME protocol as the subject-disjoint arm: original checkpoints, legacy")
L.append("% scan-level split rebuilt from dataset.py at commit 1d4ec45, five inference")
L.append("% seeds, 2000-resample bootstrap over test SUBJECTS, CPU at 16 threads.")
L.append("%")
L.append("% SUPERSEDES the \\prov single-run values in numbers.tex "
         "(\\leakDxBefore etc.).")
L.append("%")
L.append("% NOT PAIRED. The two arms have different test sets, so the difference")
L.append("% between them carries NO confidence interval. Quote each arm with its own")
L.append("% interval and the delta as a difference of point estimates.")
L.append("% " + "=" * 74)
L.append("")

for stem, st, ct, metric in SPECS:
    try:
        b = row(s, st, metric)
    except SystemExit:
        L.append(f"% {stem}: no scan-level row for {st}/{metric} — skipped")
        continue
    a = row(c, ct, metric)
    d = 100 * (b["mean"] - a["mean"])
    L.append(f"% scanlevel_summary_ci_all.csv | task={st} metric={metric} "
             f"n_seeds={int(b.n_seeds)} n_units={int(b.n_units)} "
             f"n_subjects={int(b.n_subjects)}")
    L.append(f"\\newcommand{{\\{stem}BeforeS}}{{{b['mean']:.3f}}}")
    L.append(f"\\newcommand{{\\{stem}BeforeSD}}{{{b.seed_sd:.4f}}}  "
             f"% inference-seed SD")
    L.append(f"\\newcommand{{\\{stem}BeforeCI}}{{[{b.boot_ci_lo:.3f}, "
             f"{b.boot_ci_hi:.3f}]}}  % 95% bootstrap over test subjects")
    L.append(f"\\newcommand{{\\{stem}DeltaS}}{{{d:.0f}}}  "
             f"% pp, {b['mean']:.3f} -> {a['mean']:.3f}; difference of point "
             f"estimates, NOT paired")
    L.append("")

# leakage magnitude — the mechanism the subsection asserts but never measured
L.append("% Fraction of scans in the legacy TEST set whose subject also appears in")
L.append("% the legacy TRAIN set. This is the leak itself, and it is what makes the")
L.append("% inflation task-dependent: the binary task leaks far less than the")
L.append("% fine-grained ones. Source: leaked_scan_frac in the same CSV.")
for stem, st, _, _ in SPECS:
    r = s[(s.task == st) & (s.metric == "accuracy")]
    if r.empty:
        continue
    L.append(f"\\newcommand{{\\{stem}LeakFrac}}{{{100*r.iloc[0].leaked_scan_frac:.0f}\\%}}")
L.append("")

OUT.write_text("\n".join(L) + "\n")
print(f"WROTE {OUT}  ({sum(1 for x in L if x.startswith(chr(92)+'newcommand'))} macros)")
print("\n".join(x for x in L if x.startswith("\\newcommand")))
