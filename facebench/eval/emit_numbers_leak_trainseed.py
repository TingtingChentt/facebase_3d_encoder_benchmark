#!/usr/bin/env python3
"""
Emit paper/numbers_leak_trainseed.tex — the leakage contrast with BOTH arms as
five-retraining means. thread facebase3d-figs-2026-09-04.

Same discipline as emit_numbers.py and emit_numbers_scanlevel.py: every value is
written from the CSV, never typed, and each macro carries the row it came from.
Run after aggregate_scanlevel_trainseed.py.

SUPERSEDES the \\leak*BeforeS / \\leak*After / \\leak*DeltaS macros in
numbers_leak.tex for B1 and B2. It does NOT supersede the C (combined screening)
row: C_scanlevel was not retrained -- Fig. 5(a) does not plot it -- so that arm
is still one checkpoint and Sec. 2.7 has to say so.

THE DELTA CARRIES NO INTERVAL. The two arms have different test sets. What is
reportable is separation: whether the worst of the five scan-level retrainings
still beats the best of the five subject-disjoint ones.
"""
import sys
from pathlib import Path

import pandas as pd

PROJECT = Path(__file__).resolve().parents[2]
SRC = PROJECT / "results/scanlevel_trainseed_summary.csv"
OUT = PROJECT / "results/paper_macros/numbers_leak_trainseed.tex"

if not SRC.exists():
    sys.exit(f"missing {SRC} — run aggregate_scanlevel_trainseed.py first")
s = pd.read_csv(SRC)

SPECS = [
    # (macro stem, leaked task, metric, human label)
    ("tsLeakSyn",    "B1_scanlevel", "accuracy", "19-class syndrome, accuracy"),
    ("tsLeakDx",     "B2_scanlevel", "accuracy", "33-class clinical, accuracy"),
    ("tsLeakDxFone", "B2_scanlevel", "macro_f1", "33-class clinical, macro-F1"),
]


def row(task, metric):
    r = s[(s.base_task == task) & (s.encoder == "pointnet2")
          & (s["head"] == "softmax") & (s.level == "scan")
          & (s.metric == metric)]
    if r.empty:
        sys.exit(f"no row for {task}/{metric}")
    return r.iloc[0]


L = []
L.append("% " + "=" * 74)
L.append("% numbers_leak_trainseed.tex — GENERATED by")
L.append("% facebench/eval/emit_numbers_leak_trainseed.py")
L.append("% Do not edit by hand; re-run the emitter.")
L.append("%")
L.append("% The leakage contrast with BOTH arms as five-retraining means.")
L.append("% Leaked arm:  B{1,2}_scanlevel_ts{1..5}, trained on the frozen leaky")
L.append("%              manifests under data/processed/legacy_scanlevel/ and scored")
L.append("%              by rerun_scanlevel.py --train-seed at five inference seeds,")
L.append("%              CPU/16 threads, split seed frozen at 42.")
L.append("% Correct arm: B{1,2}_corrected_ts{1..5} from the 2026-08-31 sweep.")
L.append("% Inference seeds are collapsed WITHIN each retraining before the SD is")
L.append("% taken, so FPS noise does not inflate it.")
L.append("%")
L.append("% SUPERSEDES \\leakSyn*/\\leakDx*/\\leakDxFone* in numbers_leak.tex.")
L.append("% DOES NOT supersede \\leakComb* — C_scanlevel was never retrained.")
L.append("%")
L.append("% NOT PAIRED. Different test sets by construction; no interval may be")
L.append("% attached to the difference. Use the Sep macros for a pairing-free claim.")
L.append("% " + "=" * 74)
L.append("")

for stem, task, metric, label in SPECS:
    r = row(task, metric)
    L.append(f"% scanlevel_trainseed_summary.csv | {label}")
    L.append(f"%   leaked  {task}: n_train_seeds={int(r.n_train_seeds)} "
             f"n_units={int(r.n_units)} n_subjects={int(r.n_subjects)} "
             f"leaked_scan_frac={r.leaked_scan_frac:.3f}")
    L.append(f"%   correct: mean={r.corr_mean:.4f} sd={r.corr_sd:.4f}")
    L.append(f"\\newcommand{{\\{stem}Before}}{{{r.train_seed_mean:.3f}}}")
    L.append(f"\\newcommand{{\\{stem}BeforeSD}}{{{r.train_seed_sd:.3f}}}")
    L.append(f"\\newcommand{{\\{stem}BeforeRange}}"
             f"{{[{r.train_seed_min:.3f}, {r.train_seed_max:.3f}]}}")
    L.append(f"\\newcommand{{\\{stem}After}}{{{r.corr_mean:.3f}}}")
    L.append(f"\\newcommand{{\\{stem}AfterSD}}{{{r.corr_sd:.3f}}}")
    L.append(f"\\newcommand{{\\{stem}AfterRange}}"
             f"{{[{r.corr_min:.3f}, {r.corr_max:.3f}]}}")
    L.append(f"\\newcommand{{\\{stem}Delta}}{{{r.delta_pp:.0f}}}  "
             f"% pp, difference of means, NOT paired")
    L.append(f"\\newcommand{{\\{stem}DeltaOne}}{{{r.delta_pp:.1f}}}")
    # Separation is the strongest claim available without pairing the arms.
    sep = "yes" if bool(r.separated) else "no"
    L.append(f"\\newcommand{{\\{stem}Sep}}{{{sep}}}  "
             f"% worst leaked ({r.train_seed_min:.3f}) vs best subject-disjoint "
             f"({r.corr_max:.3f})")
    if pd.notna(r.get("legacy_z")):
        L.append(f"\\newcommand{{\\{stem}LegZ}}{{{r.legacy_z:+.2f}}}  "
                 f"% single unseeded leaky checkpoint = {r.legacy_value:.3f}, "
                 f"in SD units of the retrained leaked arm")
    L.append("")

L.append("% Leak fraction — unchanged by retraining (it is a property of the")
L.append("% split, not of the model), but re-emitted here from the retrained")
L.append("% arm's own CSV so this file does not depend on numbers_leak.tex.")
for stem, task, metric, _ in SPECS:
    r = row(task, metric)
    L.append(f"\\newcommand{{\\{stem}Leak}}"
             f"{{{100 * r.leaked_scan_frac:.0f}\\%}}")
L.append("")

OUT.write_text("\n".join(L) + "\n")
n = sum(1 for x in L if x.startswith("\\newcommand"))
print(f"WROTE {OUT}  ({n} macros)")
print("\n".join(x for x in L if x.startswith("\\newcommand")))
