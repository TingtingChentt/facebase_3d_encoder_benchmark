#!/usr/bin/env python3
"""
Macros (\\cfu*) for combined affected-vs-unaffected screening (C_full_v3, early
stopping off, train seeds 1-5): scan vs subject level per encoder and the
aggregation contrasts (Supplementary Table S1 and its text).

Sources: results/cfullv3_trainseed_{summary,per_run}.csv,
         results/contrast_tests_cfullv3.csv
Writes:  results/paper_macros/numbers_cfull.tex
"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))  # repo root
import csv
import statistics as st

HERE = Path(__file__).resolve().parent
from facebench.training import task_registry as C                                    # noqa: E402


class E:
    """Formatting helpers shared with the (v1) training-seed macro emitter, inlined."""
    S1_ENC = [("Gm", "geommlp"), ("Pn", "pointnet"), ("Pt", "pointnet2"), ("Dg", "dgcnn")]
    WORDS = {0: "none of five", 1: "one of five", 2: "two of five",
             3: "three of five", 4: "four of five", 5: "all five"}

    @staticmethod
    def num(x):
        try:
            v = float(x)
            return None if v != v else v
        except (TypeError, ValueError):
            return None

    @staticmethod
    def tex(s):
        """LaTeX-safe signed number: a leading minus must be math mode."""
        return f"${s}$" if s.startswith("-") else s


TASK = "C_full_v3"
OUT = HERE.parents[1] / "results" / "paper_macros" / "numbers_cfull.tex"
SUMMARY = list(csv.DictReader(open(C.OUT / "cfullv3_trainseed_summary.csv")))
CONTRAST = list(csv.DictReader(open(C.OUT / "contrast_tests_cfullv3.csv")))
PER = list(csv.DictReader(open(C.OUT / "cfullv3_trainseed_per_run.csv")))
P2 = "pointnet2"
ENC_NAME = {"geommlp": "GeomMLP", "pointnet": "PointNet", P2: "PointNet++", "dgcnn": "DGCNN"}

CELLS = [("combAcc", P2, "scan", "accuracy"), ("combAuc", P2, "scan", "macro_auc")]
for _tag, _enc in E.S1_ENC:
    for _lvl, _lab in [("scan", "Scan"), ("subject", "Subj")]:
        for _suf, _met in [("", "accuracy"), ("F", "macro_f1"), ("A", "macro_auc")]:
            CELLS.append((f"combAgg{_tag}{_lab}{_suf}", _enc, _lvl, _met))

CONTRASTS = [("aggGainCombAcc", P2, "accuracy"), ("aggGainCombFone", P2, "macro_f1"),
             ("aggGainCombAuc", P2, "macro_auc")]
for _tag, _enc in E.S1_ENC:
    for _suf, _met in [("", "accuracy"), ("F", "macro_f1"), ("A", "macro_auc")]:
        CONTRASTS.append((f"combAggD{_tag}{_suf}", _enc, _met))


def cell(enc, level, metric):
    r = [x for x in SUMMARY if x["base_task"] == TASK and x["encoder"] == enc
         and x["head"] == "softmax" and x["level"] == level and x["metric"] == metric]
    if len(r) != 1:
        sys.exit(f"{len(r)} rows for {TASK}/{enc}/{level}/{metric}")
    return r[0]


def contrast_rows(enc, metric):
    rs = sorted([x for x in CONTRAST if x["contrast"] == f"C2_agg_softmax[{enc}]"
                 and x["task"].startswith(TASK + "_ts") and x["metric"] == metric],
                key=lambda x: x["task"])
    if len(rs) != 5:
        sys.exit(f"{len(rs)} training seeds for {enc}/{metric}")
    return rs


def series(enc, level, metric):
    rs = sorted([x for x in PER if x["base_task"] == TASK and x["encoder"] == enc
                 and x["head"] == "softmax" and x["level"] == level
                 and x["metric"] == metric], key=lambda x: int(float(x["train_seed"])))
    if len(rs) != 5:
        sys.exit(f"{len(rs)} training seeds for {enc}/{level}/{metric}")
    return [float(x["value"]) for x in rs]


def main():
    L = ["% numbers_cfull.tex — MACHINE-GENERATED by facebench/evaluation/emit_numbers_cfull.py",
         f"% task {TASK}: combined screening, 4 encoders x 5 training seeds, 200 epochs, no early stopping",
         "% \\cfuX mirrors \\tsX in paper/numbers_trainseed.tex (C_corrected, patience 20)", ""]
    for stem, enc, level, metric in CELLS:
        r = cell(enc, level, metric)
        S = stem[0].upper() + stem[1:]
        m, sd = E.num(r["train_seed_mean"]), E.num(r["train_seed_sd"])
        lo, hi = E.num(r["boot_ci_lo"]), E.num(r["boot_ci_hi"])
        mn, mx = E.num(r["train_seed_min"]), E.num(r["train_seed_max"])
        L.append(f"% {TASK}/{enc}/softmax/{level}/{metric}")
        L.append("\\newcommand{\\cfu%s}{%.3f}" % (S, m))
        L.append("\\newcommand{\\cfu%sSD}{%.3f}" % (S, sd))
        L.append("\\newcommand{\\cfu%sCIb}{[%.3f, %.3f]}" % (S, lo, hi))
        L.append("\\newcommand{\\cfu%sRange}{%.3f--%.3f}" % (S, mn, mx))
    L.append("")
    nsig_acc = {}
    for stem, enc, metric in CONTRASTS:
        rs = contrast_rows(enc, metric)
        d = [100 * float(x["diff_mean"]) for x in rs]
        nsig = sum(1 for x in rs if x["ci_contains_zero"] == "False")
        if metric == "accuracy":
            nsig_acc[enc] = nsig
        S = stem[0].upper() + stem[1:]
        L.append(f"% C2_agg_softmax[{enc}] {metric}, pp; CI excl. 0 in {nsig}/5")
        L.append("\\newcommand{\\cfu%s}{%s}" % (S, E.tex(f"{st.mean(d):+.1f}")))
        L.append("\\newcommand{\\cfu%sSD}{%.1f}" % (S, st.stdev(d)))
        L.append("\\newcommand{\\cfu%sRange}{%s to %s}"
                 % (S, E.tex(f"{min(d):+.1f}"), E.tex(f"{max(d):+.1f}")))
        L.append("\\newcommand{\\cfu%sNSig}{%s}" % (S, E.WORDS[nsig]))
    L.append("")

    # cross-encoder summaries (same rules as emit_numbers_trainseed.py)
    f1 = {e: [100 * float(x["diff_mean"]) for x in contrast_rows(e, "macro_f1")]
          for _, e in E.S1_ENC}
    f1sig = {e: sum(1 for x in contrast_rows(e, "macro_f1") if x["ci_contains_zero"] == "False")
             for _, e in E.S1_ENC}
    mags = sorted(abs(st.mean(v)) for v in f1.values())
    neg = [e for e, v in f1.items() if st.mean(v) < 0]
    L.append("% macro-F1 aggregation change: " + ", ".join(
        f"{e} {st.mean(v):+.2f} ({f1sig[e]}/5 sig)" for e, v in f1.items()))
    L.append("\\newcommand{\\cfuCombAggFoneNRev}{%s}"
             % ("all four" if len(neg) == 4 else f"{len(neg)} of four"))
    L.append("\\newcommand{\\cfuCombAggFoneRange}{%.1f to %.1f}" % (mags[0], mags[-1]))
    L.append("\\newcommand{\\cfuCombAggFoneMinSig}{%s}" % E.WORDS[min(f1sig.values())])
    au = {e: st.mean(100 * float(x["diff_mean"]) for x in contrast_rows(e, "macro_auc"))
          for _, e in E.S1_ENC}
    amag = sorted(abs(v) for v in au.values())
    L.append("% macro-AUC aggregation change: " + ", ".join(f"{e} {v:+.2f}" for e, v in au.items()))
    L.append("\\newcommand{\\cfuCombAggAucNDown}{%s}"
             % ("all four" if all(v < 0 for v in au.values())
                else f"{sum(1 for v in au.values() if v < 0)} of four"))
    L.append("\\newcommand{\\cfuCombAggAucRange}{%.1f to %.1f}" % (amag[0], amag[-1]))
    acc_all5 = [ENC_NAME[e] for _, e in E.S1_ENC if nsig_acc[e] == 5]
    acc_not = [ENC_NAME[e] for _, e in E.S1_ENC if nsig_acc[e] != 5]
    L.append("% accuracy aggregation, CI excl. 0 in all five runs: " + ", ".join(acc_all5)
             + " | not: " + ", ".join(f"{ENC_NAME[e]} {nsig_acc[e]}/5" for _, e in E.S1_ENC
                                     if nsig_acc[e] != 5))
    L.append("\\newcommand{\\cfuCombAggAccAllFive}{%s}" % ", ".join(acc_all5))
    L.append("\\newcommand{\\cfuCombAggAccNotFive}{%s}" % ", ".join(acc_not))
    L.append("")

    # PN++ vs DGCNN, paired by training seed (scan level, softmax)
    L.append("% PointNet++ minus DGCNN, paired by training seed, pp")
    for stem, level, metric in [("CombAccPtVsDg", "scan", "accuracy"),
                                ("CombAucPtVsDg", "scan", "macro_auc"),
                                ("CombAccSubjPtVsDg", "subject", "accuracy"),
                                ("CombAucSubjPtVsDg", "subject", "macro_auc")]:
        d = [100 * (a - b) for a, b in zip(series(P2, level, metric),
                                           series("dgcnn", level, metric))]
        L.append("\\newcommand{\\cfu%s}{%s}" % (stem, E.tex(f"{st.mean(d):+.1f}")))
        L.append("\\newcommand{\\cfu%sNPos}{%s}" % (stem, E.WORDS[sum(v > 0 for v in d)]))
    L.append("")
    OUT.write_text("\n".join(L))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
