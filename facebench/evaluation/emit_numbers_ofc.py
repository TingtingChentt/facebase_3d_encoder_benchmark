#!/usr/bin/env python3
"""Macros (\\tsOfc*) for the two cleft tasks: binary screening (A2_fix_v3) and
four-class subtyping (A1_fix_v3), scan level, softmax head, mean/SD over five
training seeds. Reads results/{a1fixv3,a2fixv3}_trainseed_summary.csv; writes
results/paper_macros/numbers_ofc.tex.
"""
from pathlib import Path
import pandas as pd

P = Path(__file__).resolve().parents[2]
R = P / "results"
CELLS = {  # macro: (task, encoder, metric)
    "tsOfcBinAcc": ("A2_fix_v3", "pointnet2", "accuracy"),
    "tsOfcBinAuc": ("A2_fix_v3", "pointnet2", "macro_auc"),
    "tsOfcBinAccDG": ("A2_fix_v3", "dgcnn", "accuracy"),
    "tsOfcBinAucDG": ("A2_fix_v3", "dgcnn", "macro_auc"),
    "tsOfcBinAucGM": ("A2_fix_v3", "geommlp", "macro_auc"),
    "tsOfcFourAucPt": ("A1_fix_v3", "pointnet2", "macro_auc"),
    "tsOfcFourAucDG": ("A1_fix_v3", "dgcnn", "macro_auc"),
}
ts = pd.concat([pd.read_csv(R / "a1fixv3_trainseed_summary.csv"),
                pd.read_csv(R / "a2fixv3_trainseed_summary.csv")])
L = ["% numbers_ofc.tex — GENERATED by facebench/evaluation/emit_numbers_ofc.py",
     "% cleft-task cells, 5-training-seed mean / SD", ""]
for m, (t, e, met) in CELLS.items():
    r = ts[(ts.base_task == t) & (ts.encoder == e) & (ts["head"] == "softmax")
           & (ts.level == "scan") & (ts.metric == met)]
    assert len(r) == 1 and int(r.n_train_seeds.iloc[0]) == 5, (m, len(r))
    L.append(f"% {t}/{e}/softmax/scan/{met}")
    L.append("\\newcommand{\\%s}{%.3f}" % (m, r.train_seed_mean.iloc[0]))
    L.append("\\newcommand{\\%sSD}{%.3f}" % (m, r.train_seed_sd.iloc[0]))
out = P / "results/paper_macros/numbers_ofc.tex"
out.write_text("\n".join(L) + "\n")
print("wrote", out)
