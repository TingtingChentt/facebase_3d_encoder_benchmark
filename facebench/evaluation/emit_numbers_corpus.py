#!/usr/bin/env python3
"""Corpus counts of Table 1 -> results/paper_macros/numbers_corpus.tex.

Read from the shipped ID file data/splits/scans.csv (one row per processed scan)
and the task split files; no FaceBase access needed.

  \\NScansProc, \\NSubjectsProc            processed scans / subjects, six cohorts
  \\NDatasets                             number of cohorts, as a word
  \\ds<Cohort>, \\ds<Cohort>Subj           per cohort
  \\maxScansPerSubj, \\medScansPerSubj     FB-TJ0 repeated scans (max; mean per subject)
  \\combNtest                              test scans of the combined screening task
"""
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))  # repo root
from facebench.paths import MACROS, SPLITS  # noqa: E402

CODE = {"FB-5A": "FiveA", "FB-56": "FiveSix", "FB-TJ0": "TJZeroAll", "FB-TK0": "TKZero",
        "FB-VWP": "VWP", "FB-TX4": "TXFour"}
SUBJ = {"FB-TJ0": "TJZeroSubj"}


def n(x):
    return f"{x:,}".replace(",", "{,}")


def main():
    sc = pd.read_csv(SPLITS / "scans.csv")
    L = ["% numbers_corpus.tex — GENERATED by facebench/evaluation/emit_numbers_corpus.py "
         "from data/splits/scans.csv"]
    mac = lambda k, v: L.append(f"\\newcommand{{\\{k}}}{{{v}}}")
    mac("NScansProc", n(len(sc)))
    mac("NSubjectsProc", n(sc.subject_id.nunique()))
    words = {6: "six"}
    mac("NDatasets", words.get(sc.dataset.nunique(), str(sc.dataset.nunique())))
    for ds, code in CODE.items():
        g = sc[sc.dataset == ds]
        mac(f"ds{code}", n(len(g)))
        mac(f"ds{SUBJ.get(ds, code + 'Subj')}", n(g.subject_id.nunique()))
    tj = sc[sc.dataset == "FB-TJ0"].groupby("subject_id").size()
    mac("maxScansPerSubj", str(int(tj.max())))
    mac("medScansPerSubj", f"{tj.mean():.1f}")
    c = pd.read_csv(SPLITS / "C_full_v3.csv")
    mac("combNtest", n(int((c.split == "test").sum())))
    MACROS.mkdir(parents=True, exist_ok=True)
    (MACROS / "numbers_corpus.tex").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
