"""
LaTeX macros for the region-occlusion interpretability text.
Writes results/paper_macros/numbers_interp.tex from the shipped aggregate tables
results/interp/tables/{syndrome_region_all_subjects,analysis_counts}.csv. When the
local scan lists and occlusion scores exist (a full rebuild), analysis_counts.csv
is recomputed from them first.

  \\interpNScans, \\interpNScansLm      test scans of the analysed syndromes / with landmarks
  \\interpNSubj, \\interpNSubjLm, \\interpNSyn
  \\interpMainNScans ... same for the five main-figure syndromes
  \\ipm<Syn><Region>, \\ipp<Syn><Region>, \\ipn<Syn>  mean importance, % subjects positive, n subjects
      (subset = all test subjects of the syndrome, correct or not)
"""
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))  # repo root
from facebench.paths import MACROS, RESULTS  # noqa: E402

IN = RESULTS / "interp"
OUT = MACROS / "numbers_interp.tex"
COUNTS = IN / "tables/analysis_counts.csv"
SYN = {"Achondroplasia": "Achon", "Cockayne Syndrome": "Cock", "Down Syndrome": "Down",
       "Pallister-Killian Syndrome": "PKS", "Rhizomelic Chondrodysplasia Punctata": "RCDP",
       "Mucopolysaccharidosis": "MPS", "Phelan McDermid Syndrome": "PMS"}
MAIN = list(SYN)[:5]
REG = {"forehead": "Forehead", "periorbital": "Periorbital", "nose": "Nose", "cheek": "Cheek",
       "philtrum": "Philtrum", "lips": "Lips", "chin_jaw": "Chin"}


def analysis_counts():
    """Scans / subjects analysed (and with landmarks), as an aggregate table."""
    lists = [IN / "pilot_scans.csv", IN / "ext_scans.csv"]
    occ = [IN / "pilot/region_occlusion.csv", IN / "ext/region_occlusion.csv"]
    if all(f.exists() for f in lists + occ):
        scans = pd.concat([pd.read_csv(f) for f in lists]).drop_duplicates("scan_id")
        oc = pd.concat([pd.read_csv(f) for f in occ])
        scans["lm"] = scans.scan_id.isin(oc.scan_id)
        main_ = scans[scans.syndrome_name.isin(MAIN)]
        m = {"interpNSyn": scans.syndrome_name.nunique(),
             "interpNScans": len(scans), "interpNScansLm": int(scans.lm.sum()),
             "interpNSubj": scans.fbid.nunique(), "interpNSubjLm": scans[scans.lm].fbid.nunique(),
             "interpMainNScans": len(main_), "interpMainNScansLm": int(main_.lm.sum()),
             "interpMainNSubj": main_.fbid.nunique(), "interpMainNSubjLm": main_[main_.lm].fbid.nunique()}
        pd.Series(m, name="value").rename_axis("macro").reset_index().to_csv(COUNTS, index=False)
    return dict(pd.read_csv(COUNTS).values)


def main():
    m = analysis_counts()
    t = pd.read_csv(IN / "tables/syndrome_region_all_subjects.csv")
    t = t[t.subset == "all"]
    for syn, code in SYN.items():
        s = t[t.syndrome == syn]
        m[f"ipn{code}"] = int(s.n_subjects.iloc[0])
        for _, r in s.iterrows():
            m[f"ipm{code}{REG[r.region]}"] = f"${r['mean']:+.3f}$"
            m[f"ipp{code}{REG[r.region]}"] = f"{100 * r.frac_positive:.0f}\\%"
    lines = ["% generated by analyses/interpretability/write_numbers_interp.py -- do not edit by hand"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in m.items()]
    OUT.write_text("\n".join(lines) + "\n")
    print(OUT, len(m), "macros")


if __name__ == "__main__":
    main()
