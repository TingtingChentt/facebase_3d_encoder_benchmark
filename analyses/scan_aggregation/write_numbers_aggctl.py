#!/usr/bin/env python3
"""results/paper_macros/numbers_aggctl.tex from results/scan_aggregation/.
Macros prefixed \\ag. All values read from scan_count_controlled.py outputs."""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))  # repo root
from facebench.paths import MACROS, RESULTS  # noqa: E402

R = RESULTS / "scan_aggregation"
rec = pd.read_csv(R / "per_subject_by_m.csv.gz", dtype={"m": str})
scan = pd.read_csv(R / "scan_level_per_seed.csv")
con = pd.read_csv(R / "AC_paired_contrasts.csv")
cur = pd.read_csv(R / "AC_same_patient_curves.csv", dtype={"m": str})
tr = pd.read_csv(R / "B_pair_transitions.csv").set_index("head")
dirn = pd.read_csv(R / "B_patient_direction.csv")
L = ["% numbers_aggctl.tex — GENERATED by analyses/scan_aggregation/write_numbers_aggctl.py",
     "% Controlled same-patient aggregation analysis."]
H = {"softmax": "SM", "proto": "Pr"}


def mac(n, v):
    L.append("\\newcommand{\\ag%s}{%s}" % (n, v))


pp = lambda x: f"{100 * x:.1f}"
f3 = lambda x: f"{x:.3f}"
f2 = lambda x: f"{x:.2f}"

# --- decomposition (per run; inference seeds averaged within run) ---------
for h, t in H.items():
    s = scan[scan["head"] == h].groupby("run").top1.mean()
    one = rec[(rec["head"] == h) & (rec.m == "1")].groupby(["run", "seed"]).top1.mean().groupby("run").mean()
    al = rec[(rec["head"] == h) & (rec.m == "all")].groupby(["run", "seed"]).top1.mean().groupby("run").mean()
    mac(f"ScanTop{t}", f3(s.mean())); mac(f"OneTop{t}", f3(one.mean())); mac(f"OneTop{t}SD", f3(one.std()))
    mac(f"AllTop{t}", f3(al.mean()))
    mac(f"UnitGain{t}", pp((one - s).mean())); mac(f"UnitGain{t}SD", pp((one - s).std()))
    mac(f"CombGain{t}", pp((al - one).mean())); mac(f"CombGain{t}SD", pp((al - one).std()))
    mac(f"TotGain{t}", pp((al - s).mean()))
    mac(f"CombShare{t}", f"{100 * (al - one).mean() / (al - s).mean():.0f}")
    x = rec[(rec["head"] == h) & (rec.m == "1")].copy()
    x["single"] = x.n_scans == 1
    g = x.groupby(["single", "run", "seed"]).top1.mean().groupby(["single", "run"]).mean().groupby("single").mean()
    mac(f"SingleSubjTop{t}", f3(g[True])); mac(f"MultiSubjTop{t}", f3(g[False]))

n_by = rec[rec.m == "1"].groupby("subject").n_scans.first()
mac("NSingle", int((n_by == 1).sum()))
for k, w in zip((2, 3, 4, 5), ("Two", "Three", "Four", "Five")):
    mac(f"N{w}Plus", int((n_by >= k).sum()))
    mac(f"N{w}PlusCls", int(rec[(rec.m == "1") & (rec.n_scans >= k)].label.nunique()))

# --- paired contrasts ------------------------------------------------------
def C(h, coh, c):
    return con[(con["head"] == h) & (con.cohort == coh) & (con.contrast == c)].iloc[0]


def pfmt(p):
    e = int(np.floor(np.log10(p)))
    return f"{p / 10 ** e:.1f}\\times10^{{{e}}}"


for h, t in H.items():
    r = C(h, ">=2 scans", "2 vs 1")
    mac(f"OneTwoTop{t}", pp(r.d_top1)); mac(f"OneTwoTop{t}SD", pp(r.d_top1_sd))
    mac(f"OneTwoTop{t}CI", f"{pp(r.d_top1_ci_lo)}--{pp(r.d_top1_ci_hi)}")
    mac(f"OneTwoTopFive{t}", pp(r.d_top5))
    mac(f"OneTwoRank{t}", f2(-r.d_mean_rank)); mac(f"OneTwoRank{t}SD", f2(r.d_mean_rank_sd))
    mac(f"OneTwoRank{t}CI", f"{f2(-r.d_mean_rank_ci_hi)}--{f2(-r.d_mean_rank_ci_lo)}")
    mac(f"OneTwoRank{t}P", "$" + pfmt(r.d_mean_rank_wilcoxon_p) + "$")
    r = C(h, ">=2 scans", "all vs 1")
    mac(f"OneAllTop{t}", pp(r.d_top1)); mac(f"OneAllRank{t}", f2(-r.d_mean_rank))
    # curves
    for coh, w, ms in ((">=2 scans", "Two", "12"), (">=4 scans", "Four", "1234"), (">=5 scans", "Five", "12345")):
        c = cur[(cur["head"] == h) & (cur.cohort == coh)].set_index("m")
        for m in ms + "a":
            mm = "all" if m == "a" else m
            tag = "All" if m == "a" else ["", "One", "Two", "Three", "Four", "Five"][int(m)]
            mac(f"Cur{w}{tag}Top{t}", f3(c.loc[mm, "top1_mean"]))
            mac(f"Cur{w}{tag}Rank{t}", f"{c.loc[mm, 'mean_rank_mean']:.1f}")
    for w, steps in (("Four", ("2 vs 1", "3 vs 2", "4 vs 3")), ("Five", ("2 vs 1", "3 vs 2", "4 vs 3", "5 vs 4"))):
        coh = f">={len(steps) + 1} scans"
        mac(f"Steps{w}Top{t}", ", ".join(f"+{pp(C(h, coh, s).d_top1)}" for s in steps))
        mac(f"Steps{w}Rank{t}", ", ".join(f"{f2(-C(h, coh, s).d_mean_rank)}" for s in steps))
        mac(f"Steps{w}MinRuns{t}", int(min(C(h, coh, s).d_top1_runs_improved for s in steps)))
        mac(f"Steps{w}MaxP{t}", "$" + pfmt(max(C(h, coh, s).d_mean_rank_wilcoxon_p for s in steps)) + "$")
    # transitions (percent of patient-weighted ordered pairs)
    for k, n in (("wrong_to_right", "Fix"), ("right_to_wrong", "Break"), ("right_to_right", "Keep"),
                 ("wrong_to_wrong", "Miss"), ("rank_up", "Up"), ("rank_down", "Down"), ("rank_same", "Same")):
        mac(f"Tr{n}{t}", pp(tr.loc[h, f"{k}_mean"]))
    d = dirn[(dirn["head"] == h)].set_index("tolerance_rank")
    mac(f"PatImp{t}", int(d.loc[0.0, "improved"])); mac(f"PatWor{t}", int(d.loc[0.0, "worsened"]))
    mac(f"PatImpOne{t}", int(d.loc[1.0, "improved"])); mac(f"PatWorOne{t}", int(d.loc[1.0, "worsened"]))
    mac(f"PatImpHalf{t}", int(d.loc[0.5, "improved"])); mac(f"PatWorHalf{t}", int(d.loc[0.5, "worsened"]))
    mac(f"PatSameHalf{t}", int(d.loc[0.5, "unchanged"])); mac(f"PatSameOne{t}", int(d.loc[1.0, "unchanged"]))
    mac(f"PatSame{t}", int(d.loc[0.0, "unchanged"]))
    mac(f"PatMedRank{t}", f2(-d.loc[0.0, "median_d_rank"]))

MACROS.mkdir(parents=True, exist_ok=True)
(MACROS / "numbers_aggctl.tex").write_text("\n".join(L) + "\n")
print("\n".join(L))
