#!/usr/bin/env python3
"""results/paper_tables/table_s_aggctl_steps.tex: scan-by-scan increments of the controlled
same-patient aggregation analysis. All values read from
results/scan_aggregation/AC_paired_contrasts.csv (scan_count_controlled.py)."""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))  # repo root
from facebench.paths import RESULTS  # noqa: E402

TABLES = RESULTS / "paper_tables"
con = pd.read_csv(RESULTS / "scan_aggregation/AC_paired_contrasts.csv")
HL = {"softmax": "Softmax inference (class probabilities averaged)",
      "proto": "Prototype inference (embeddings averaged)"}
COH = [">=2 scans", ">=3 scans", ">=4 scans", ">=5 scans"]


def pf(p):
    if p >= 1e-3:
        return f"{p:.3f}" if p >= 0.01 else f"{p:.4f}"
    e = int(np.floor(np.log10(p)))
    return f"${p / 10 ** e:.1f}\\times10^{{{e}}}$"


def order(c):
    a, b = c.split(" vs ")
    return (a == "all" or (int(b) == 1 and int(a) > 2), int(b) if b.isdigit() else 0)


rows = []
for h in ("softmax", "proto"):
    rows.append(f"\\multicolumn{{8}}{{l}}{{\\textit{{{HL[h]}}}}} \\\\")
    for coh in COH:
        sub = con[(con["head"] == h) & (con.cohort == coh)]
        sub = sub.iloc[sorted(range(len(sub)), key=lambda i: order(sub.contrast.iloc[i]))]
        first = True
        for _, r in sub.iterrows():
            a, b = r.contrast.split(" vs ")
            comp = f"{'all' if a == 'all' else a} vs {b}"
            lab = coh.replace(">=", "$\\geq$") if first else ""
            n = str(int(r.n_patients)) if first else ""
            first = False
            rk, lo, hi = -r.d_mean_rank, -r.d_mean_rank_ci_hi, -r.d_mean_rank_ci_lo
            runs = min(int(r.d_top1_runs_improved), int(r.d_mean_rank_runs_improved))
            rows.append(" & ".join([lab, n, comp,
                                    f"{100 * r.d_top1:+.1f} ({100 * r.d_top1_ci_lo:.1f} to {100 * r.d_top1_ci_hi:.1f})",
                                    pf(r.d_top1_wilcoxon_p),
                                    f"{rk:+.2f} ({lo:.2f} to {hi:.2f})",
                                    pf(r.d_mean_rank_wilcoxon_p), f"{runs}/5"]) + " \\\\")
        rows.append("\\addlinespace")
    rows.append("\\midrule" if h == "softmax" else "")

tex = r"""% GENERATED by analyses/scan_aggregation/write_supp_table_aggctl.py — do not edit by hand
\begin{table}[h]
\centering
\caption{\textbf{Scan-by-scan increments in the controlled same-patient aggregation analysis.}
PointNet++ on the 49-class syndrome-diagnosis task (existing models, no retraining). Each block uses a
fixed set of patients with at least the stated number of scans; ``$m$ vs $m-1$'' compares $m$ with $m-1$ scans
of the same patients (all subsets of each size, or 300 random subsets), and ``all vs 1'' / ``$k$ vs 1''
compares all or $k$ scans with a single scan. $\Delta$top-1, change in top-1 accuracy (percentage points);
$\Delta$rank, number of positions the true syndrome moved up among the 49 candidate diagnoses (positive =
improvement). Values are means across five trained models (inference seeds averaged within each model);
95\% confidence intervals from 2,000 bootstrap resamples of patients applied to per-patient differences averaged
across models; $P$, two-sided Wilcoxon signed-rank test on the same per-patient differences. Runs, number of
trained models in which both $\Delta$top-1 and $\Delta$rank were positive.}
\label{tab:s_aggctl_steps}
\footnotesize
\setlength{\tabcolsep}{3.5pt}
\begin{tabular}{lrl r l r l c}
\toprule
Patients & $n$ & Scans & $\Delta$top-1, pp (95\% CI) & $P$ & $\Delta$rank (95\% CI) & $P$ & Runs \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{table}
"""
TABLES.mkdir(parents=True, exist_ok=True)
(TABLES / "table_s_aggctl_steps.tex").write_text(tex)
print(tex)
