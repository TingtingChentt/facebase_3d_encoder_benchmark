#!/usr/bin/env python3
"""results/paper_macros/numbers_protoret.tex from results/prioritization/.
Macros prefixed \\pq. All values read from proto_retrieval.py outputs."""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))  # repo root
from facebench.paths import MACROS, RESULTS  # noqa: E402

R = RESULTS / "prioritization"
A = pd.read_csv(R / "A_summary.csv").set_index("head")
Ac = pd.read_csv(R / "A_proto_vs_softmax.csv").set_index("metric")
Bs = pd.read_csv(R / "B_summary.csv").iloc[0]
Bch = pd.read_csv(R / "B_chance.csv").set_index("k")
Bvs = pd.read_csv(R / "B_vs_proto_topk.csv").set_index("k")
Cs = pd.read_csv(R / "C_summary.csv", dtype={"n_ref": str}).set_index("n_ref")
Cv = pd.read_csv(R / "C_vs_all.csv", dtype={"n_ref": str})
sz = pd.read_csv(R / "class_sizes.csv")
L = ["% numbers_protoret.tex — GENERATED by analyses/prioritization/write_numbers_protoret.py",
     "% Diagnostic prioritization (top-K, patient retrieval, limited reference)."]
H = {"softmax": "SM", "proto": "Pr"}
W = {1: "One", 2: "Two", 3: "Three", 5: "Five", 10: "Ten"}


def mac(n, v):
    L.append("\\newcommand{\\pq%s}{%s}" % (n, v))


pp = lambda x: f"{100 * x:.1f}"
f3 = lambda x: f"{x:.3f}"
f2 = lambda x: f"{x:.2f}"


def ci_abs(lo, hi):
    """CI of a negative difference, reported as a positive shortfall; crossing 0 kept signed."""
    a, b = -hi, -lo
    return f"{pp(a)}--{pp(b)}" if a >= 0 else f"${pp(a)}$ to {pp(b)}"


def pfmt(p):
    e = int(np.floor(np.log10(p)))
    return f"{p / 10 ** e:.1f}\\times10^{{{e}}}"


# ---- A. candidate coverage ----
for h, t in H.items():
    for k in (1, 2, 3, 5, 10):
        mac(f"Top{W[k]}{t}", f3(A.loc[h, f"top{k}_mean"])); mac(f"Top{W[k]}{t}SD", f3(A.loc[h, f"top{k}_sd"]))
        mac(f"MacTop{W[k]}{t}", f3(A.loc[h, f"macro_top{k}_mean"]))
    mac(f"Mrr{t}", f3(A.loc[h, "mrr_mean"])); mac(f"Mrr{t}SD", f3(A.loc[h, "mrr_sd"]))
    mac(f"MacMrr{t}", f3(A.loc[h, "macro_mrr_mean"]))
    mac(f"Rank{t}", f"{A.loc[h, 'mean_rank_mean']:.1f}")
for k in (1, 3, 5, 10):
    r = Ac.loc[f"top{k}"]
    mac(f"DTop{W[k]}", pp(r.d_mean)); mac(f"DTop{W[k]}CI", f"{pp(r.ci_lo)}--{pp(r.ci_hi)}")
    mac(f"DTop{W[k]}P", "$" + pfmt(r.wilcoxon_p) + "$"); mac(f"DTop{W[k]}Runs", int(r.runs_proto_better))
    mac(f"DMacTop{W[k]}", pp(A.loc["proto", f"macro_top{k}_mean"] - A.loc["softmax", f"macro_top{k}_mean"]))
    mac(f"ChanceTop{W[k]}", f3(k / 49))
mac("DMrr", f3(Ac.loc["mrr"].d_mean)); mac("DMrrCI", f"{f3(Ac.loc['mrr'].ci_lo)}--{f3(Ac.loc['mrr'].ci_hi)}")
mac("DMrrP", "$" + pfmt(Ac.loc["mrr"].wilcoxon_p) + "$")
topk = Ac[Ac.index.str.match(r"top\d+$")]
mac("MaxTopKP", "$" + pfmt(topk.wilcoxon_p.max()) + "$")
mac("NTopKAllRuns", int((topk.runs_proto_better == 5).sum()))
mac("MinDTopKCILo", pp(topk.ci_lo.min()))

# ---- B. patient retrieval ----
for k in (1, 3, 5, 10):
    mac(f"Rec{W[k]}", f3(Bs[f"recall@{k}_mean"])); mac(f"Rec{W[k]}SD", f3(Bs[f"recall@{k}_sd"]))
    mac(f"Prec{W[k]}", f3(Bs[f"precision@{k}_mean"])); mac(f"Prec{W[k]}SD", f3(Bs[f"precision@{k}_sd"]))
    mac(f"MacRec{W[k]}", f3(Bs[f"macro_recall@{k}_mean"])); mac(f"MacPrec{W[k]}", f3(Bs[f"macro_precision@{k}_mean"]))
    mac(f"NDx{W[k]}", f"{Bs[f'n_distinct_dx@{k}_mean']:.1f}")
    mac(f"ChRec{W[k]}", f3(Bch.loc[k].chance_recall)); mac(f"ChPrec{W[k]}", f3(Bch.loc[k].chance_precision))
    mac(f"PrecFold{W[k]}", f"{Bs[f'precision@{k}_mean'] / Bch.loc[k].chance_precision:.0f}")
    v = Bvs.loc[k]
    # emitted as a SHORTFALL (patient Recall@K below prototype top-K): positive = lower
    mac(f"RecVsProto{W[k]}", pp(-v.d)); mac(f"RecVsProto{W[k]}CI", ci_abs(v.ci_lo, v.ci_hi))
    mac(f"RecVsProto{W[k]}P", "$" + pfmt(v.wilcoxon_p) + "$")
mac("NTrainSubj", f"{int(sz.n_train_patients.sum()):,}".replace(",", "{,}"))

# ---- C. limited reference ----
for n, w in (("1", "One"), ("3", "Three"), ("5", "Five"), ("10", "Ten"), ("all", "All")):
    r = Cs.loc[n]
    for m in ("top1", "top5", "mrr", "macro_top5"):
        nm = {"top1": "TopOne", "top5": "TopFive", "mrr": "Mrr", "macro_top5": "MacTopFive"}[m]
        mac(f"Ref{w}{nm}", f3(r[f"{m}_mean"])); mac(f"Ref{w}{nm}SD", f3(r[f"{m}_sd_runs"]))
        if n != "all":
            mac(f"Ref{w}{nm}Rng", f"{f3(r[f'{m}_q025'])}--{f3(r[f'{m}_q975'])}")
    if n != "all":
        for m, nm in (("top1", "TopOne"), ("top5", "TopFive")):
            c = Cv[(Cv.n_ref == n) & (Cv.metric == m)].iloc[0]
            # emitted as a SHORTFALL relative to all reference patients: positive = lower
            mac(f"Ref{w}D{nm}", pp(-c.d)); mac(f"Ref{w}D{nm}CI", ci_abs(c.ci_lo, c.ci_hi))
        mac(f"Ref{w}ShareTopFive", f"{100 * r.top5_mean / Cs.loc['all'].top5_mean:.0f}")
        mac(f"Ref{w}ShareTopOne", f"{100 * r.top1_mean / Cs.loc['all'].top1_mean:.0f}")
mac("RefOneFoldTopOne", f"{Cs.loc['1'].top1_mean / (1 / 49):.0f}")
mac("RefOneFoldTopFive", f"{Cs.loc['1'].top5_mean / (5 / 49):.1f}")
mac("NDraws", 50)
mac("MinTrainPerCls", int(sz.n_train_patients.min())); mac("MaxTrainPerCls", int(sz.n_train_patients.max()))
mac("MinTestPerCls", int(sz.n_test_patients.min())); mac("MaxTestPerCls", int(sz.n_test_patients.max()))

MACROS.mkdir(parents=True, exist_ok=True)
(MACROS / "numbers_protoret.tex").write_text("\n".join(L) + "\n")
print("\n".join(L))
