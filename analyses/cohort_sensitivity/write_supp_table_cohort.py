#!/usr/bin/env python3
"""
Supplementary table: every cohort-sensitivity number of Results sec:cohort, with n and CIs.
Reads results/cohort_sensitivity/*.csv only.
Writes results/paper_tables/table_s_cohort_sensitivity.tex.

PointNet++ rows: existing combined-task models, subject level, softmax.
  mean +- SD over 5 training runs (each = mean over its 5 inference seeds; paper convention);
  ensemble = 25-model mean score, 95% CI = percentile bootstrap over subjects (2,000 resamples).
Comparison predictors: cohort identity only and age(+sex) logistic regression fit on non-test subjects;
  cross-validated logistic models fit within the test subjects of the cohort (5-fold x 20 repeats).
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))  # repo root
from facebench.paths import RESULTS  # noqa: E402

R = RESULTS / "cohort_sensitivity"
TABLES = RESULTS / "paper_tables"
w = pd.read_csv(R / "within_cohort_per_run.csv").query("encoder == 'pointnet2'")
ens = pd.read_csv(R / "pn2_ensemble_auc_ci.csv").set_index("subset")
aa = pd.read_csv(R / "age_adjusted.csv").set_index(["cohort", "subset"])
ps = pd.read_csv(R / "age_adjusted_per_seed.csv")
b = pd.read_csv(R / "baselines.csv").set_index(["predictor", "subset"])

GROUPS = [  # label, within_cohort subset key, age_adjusted cohort key
    ("Combined screening (all cohorts)", "all", None),
    ("FB-TJ0 (syndromic)", "FB-TJ0 only", "FB-TJ0"),
    ("Cleft cohorts (FB-5A + FB-56)", "cleft cohorts (FB-5A + FB-56)", "cleft (FB-5A + FB-56)"),
    ("FB-5A", "FB-5A only", "FB-5A"),
    ("FB-56", "FB-56 only", "FB-56"),
]
AGE_SUBSETS = [("PointNet++, age/sex-matched$^{a}$", "age/sex matched (|diff| <= 2 y)"),
               ("PointNet++, age $<$18 y", "age < 18 y")]
# 2026-11-04: rows for age 5-17 y and the non-test age+sex model dropped (not cited; still in the csvs)

f3 = lambda x: f"{x:.3f}"
ms = lambda v: f"{np.mean(v):.3f} $\\pm$ {np.std(v, ddof=1):.3f}"
ci = lambda a, lo, hi: f"{a:.3f} [{lo:.3f}, {hi:.3f}]"
age = lambda x: "n/a" if pd.isna(x) else f"{x:.1f}"

lines = []
for lab, wk, ak in GROUPS:
    lines.append(f"\\multicolumn{{5}}{{l}}{{\\textit{{{lab}}}}}\\\\")
    r = w[w.subset == wk]
    n, na = int(r.n.iloc[0]), int(r.n_aff.iloc[0])
    e = ens.loc[wk]
    ag = aa.loc[(ak, "all ages")] if ak else None
    agecell = f"{age(ag.age_med_aff)} / {age(ag.age_med_unaff)}" if ak else "--"
    lines.append(f"\\quad PointNet++, all test subjects & {na:,} / {n - na:,} & {agecell} & {ms(r.auc)} & "
                 f"{ci(e.auc_ensemble, e.ci_lo, e.ci_hi)}\\\\")
    if ak:
        for slab, sk in AGE_SUBSETS:
            a = aa.loc[(ak, sk)]
            v = ps[(ps.cohort == ak) & (ps.subset == sk)].auc_face
            assert len(v) == 5
            lines.append(f"\\quad {slab} & {int(a.n_aff)} / {int(a.n_unaff)} & "
                         f"{age(a.age_med_aff)} / {age(a.age_med_unaff)} & {ms(v)} & {ci(a.auc_face, a.ci_lo, a.ci_hi)}\\\\")
    if wk not in ("FB-5A only", "FB-56 only"):   # trivially 0.5 within a single cohort; shown for TJ0 as reference
        lines.append(f"\\quad Cohort identity only & {na:,} / {n - na:,} & -- & "
                     f"{f3(b.loc[('cohort membership only', wk), 'auc'])} & --\\\\")
    lines.append(f"\\quad Age only$^{{b}}$ & {int(b.loc[('age only', wk), 'n']):,} total & -- & "
                 f"{f3(b.loc[('age only', wk), 'auc'])} & --\\\\")
    if ak:
        v = ps[(ps.cohort == ak) & (ps.subset == "all ages")]
        nn = f"{int(aa.loc[(ak, 'all ages')].n_aff)} / {int(aa.loc[(ak, 'all ages')].n_unaff)}"
        lines.append(f"\\quad Age + sex, CV$^{{c}}$ & {nn} & -- & {f3(v['cv_auc_age+sex'].mean())} & --\\\\")
        lines.append(f"\\quad Age + sex + PointNet++, CV$^{{c}}$ & {nn} & -- & "
                     f"{ms(v['cv_auc_age+sex+face'])} & {f3(aa.loc[(ak, 'all ages'), 'cv_auc_age+sex+face'])}\\\\")
    lines.append("\\addlinespace")
lines = lines[:-1]

tex = r"""% GENERATED by analyses/cohort_sensitivity/write_supp_table_cohort.py from results/cohort_sensitivity/*.csv
\begin{table}[h]\centering\footnotesize\ifrevmarks\color{red}\fi
\caption{\textbf{Within-cohort, demographic-adjusted and baseline screening performance.}
All PointNet++ values use the existing combined-task models and their test-set predictions at subject level; the models were not retrained, and each row changes only the subset of test subjects used to compute the AUC. Mean $\pm$ SD is across five independently trained models (each averaged over five inference seeds); ensemble AUCs use the score averaged over all 25 model--inference-seed combinations, with a 95\% percentile bootstrap confidence interval over subjects (2,000 resamples). $n$ is the number of affected / unaffected test subjects; ages are medians in years.
$^{a}$Each affected subject matched 1:1, without replacement, to an unaffected subject of the same cohort and sex with an age difference $\leq$2 years.
$^{b}$Logistic regression on age, fit on the non-test subjects of the same cohort(s) and evaluated on the test subjects with age and sex recorded.
$^{c}$Logistic regression, stratified five-fold cross-validation within the test subjects, repeated 20 times; for the model including the PointNet++ score, mean $\pm$ SD across training runs and the ensemble value.}
\label{tab:s_cohort_sensitivity}
{\setlength{\tabcolsep}{4pt}
\begin{tabular}{>{\raggedright\arraybackslash}p{5.2cm}ccll}\toprule
Evaluation & $n$ & Median age, y & AUC & Ensemble AUC\\
 & (aff./unaff.) & (aff./unaff.) & mean $\pm$ SD & [95\% CI]\\\midrule
""" + "\n".join(lines) + r"""
\bottomrule\end{tabular}}
\end{table}
"""
TABLES.mkdir(parents=True, exist_ok=True)
(TABLES / "table_s_cohort_sensitivity.tex").write_text(tex)
print(tex)
